-- Requires PostgreSQL 15+ (UNIQUE NULLS NOT DISTINCT).
--
-- Every table has created_at, updated_at, is_deleted and deleted_at. Rows are never removed:
-- a delete is `UPDATE ... SET is_deleted = true`. The trigger below keeps updated_at and
-- deleted_at right, including for changes made by hand in the database.

CREATE FUNCTION set_audit_columns() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    IF NEW.is_deleted AND NOT OLD.is_deleted THEN
        NEW.deleted_at := now();
    ELSIF NOT NEW.is_deleted THEN
        NEW.deleted_at := NULL;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE users (
    id         UUID PRIMARY KEY     DEFAULT gen_random_uuid(),
    email      TEXT,
    username   TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN     NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    -- Arts without email and username have no user (artist_id NULL = anonymous).
    CONSTRAINT users_email_or_username_present CHECK (email IS NOT NULL OR username IS NOT NULL),
    CONSTRAINT users_deleted_at_matches_is_deleted CHECK (is_deleted = (deleted_at IS NOT NULL))
);

-- A user is the pair (email, username). NULL counts as a value, so (a@x.com, NULL) and
-- (a@x.com, 'mano') are two different users and the same pair can't exist twice among the
-- users that are not deleted. A deleted user's pair can be used by a new user.
CREATE UNIQUE INDEX users_email_username_unique
    ON users (email, username) NULLS NOT DISTINCT
    WHERE NOT is_deleted;

CREATE TRIGGER users_set_audit_columns
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_audit_columns();

CREATE TABLE map_arts (
    id                             UUID PRIMARY KEY, -- generated by the Android/web app
    title                          TEXT             NOT NULL,
    latitude                       DOUBLE PRECISION NOT NULL,
    longitude                      DOUBLE PRECISION NOT NULL,
    date_in_millis                 BIGINT           NOT NULL, -- when the art was created on the device
    image_key                      TEXT             NOT NULL, -- object key in the bucket, URL = publicBaseUrl/image_key
    -- Worked out by the API from the coordinates when the art is saved (Natural Earth country borders).
    -- OCEAN when the art isn't on or near any country, UNKNOWN when the lookup failed. Fixed by hand when wrong.
    continent                      TEXT             NOT NULL,
    -- ISO 3166-1 alpha-2 code of that country. NULL in the ocean or where Natural Earth has no code (e.g. Somaliland).
    country_code                   TEXT,
    -- Art style (Android SketchArtType). NULL only for arts created before the apps recorded it.
    sketch_art_type                TEXT,
    -- Name of the palette used (COLORFUL_MAP only). A snapshot of the name, not a foreign key:
    -- the art keeps it even if the palette is deleted later.
    color_palette                  TEXT,
    -- Color the colorful map sketch gave each map layer (Android MapLayersColors), '#RRGGBB'
    map_layer_roads_color          TEXT,
    map_layer_building_stroke_color TEXT,
    map_layer_building_color       TEXT,
    map_layer_roads_path_color     TEXT,
    map_layer_water_color          TEXT,
    map_layer_land_others_color    TEXT,
    -- Users are soft deleted, so this is normally kept. SET NULL only applies if a user row is
    -- ever removed for real. Deleting an art never deletes its user.
    artist_id                      UUID REFERENCES users (id) ON DELETE SET NULL,
    is_approved_for_the_exhibition BOOLEAN          NOT NULL DEFAULT FALSE, -- changed by hand in the database
    created_at                     TIMESTAMPTZ      NOT NULL DEFAULT now(), -- when the API received it
    updated_at                     TIMESTAMPTZ      NOT NULL DEFAULT now(),
    is_deleted                     BOOLEAN          NOT NULL DEFAULT FALSE,
    deleted_at                     TIMESTAMPTZ,
    CONSTRAINT map_arts_latitude_range CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT map_arts_longitude_range CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT map_arts_sketch_art_type_valid CHECK (
        sketch_art_type IN ('DEFAULT', 'POINTILLISM', 'COLORFUL_MAP', 'WATER_FLOW', 'PARTICLE_SYSTEM')
    ),
    CONSTRAINT map_arts_continent_valid CHECK (
        continent IN ('AFRICA', 'ANTARCTICA', 'ASIA', 'CENTRAL_AMERICA', 'EUROPE', 'NORTH_AMERICA', 'OCEANIA',
                      'SOUTH_AMERICA', 'OCEAN', 'UNKNOWN')
    ),
    CONSTRAINT map_arts_country_code_format CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT map_arts_map_layer_colors_hex CHECK (
        coalesce(map_layer_roads_color, '#000000') ~ '^#[0-9A-F]{6}$' AND
        coalesce(map_layer_building_stroke_color, '#000000') ~ '^#[0-9A-F]{6}$' AND
        coalesce(map_layer_building_color, '#000000') ~ '^#[0-9A-F]{6}$' AND
        coalesce(map_layer_roads_path_color, '#000000') ~ '^#[0-9A-F]{6}$' AND
        coalesce(map_layer_water_color, '#000000') ~ '^#[0-9A-F]{6}$' AND
        coalesce(map_layer_land_others_color, '#000000') ~ '^#[0-9A-F]{6}$'
    ),
    CONSTRAINT map_arts_deleted_at_matches_is_deleted CHECK (is_deleted = (deleted_at IS NOT NULL))
);

CREATE TRIGGER map_arts_set_audit_columns
    BEFORE UPDATE ON map_arts
    FOR EACH ROW EXECUTE FUNCTION set_audit_columns();

-- The exhibition only reads approved arts that are not deleted
CREATE INDEX map_arts_exhibition_idx ON map_arts (date_in_millis DESC)
    WHERE is_approved_for_the_exhibition AND NOT is_deleted;
CREATE INDEX map_arts_artist_id_idx ON map_arts (artist_id);


-- Color palettes for the COLORFUL_MAP art style. The API is the single source: the Android and
-- web apps fetch them from GET /color-palettes instead of keeping their own lists.

CREATE TABLE color_palettes (
    id         UUID PRIMARY KEY     DEFAULT gen_random_uuid(),
    -- The apps save the selected palette by name, so a name is never changed once published.
    name       TEXT        NOT NULL,
    -- Exactly 6 colors as '#RRGGBB' (uppercase): the colorful map sketch uses indexes 0 to 5.
    colors     TEXT[]      NOT NULL,
    -- Order shown in the apps. The first available palette (lowest position) is the default.
    position   INTEGER     NOT NULL,
    -- Offered by GET /color-palettes. Changed by hand for campaigns (e.g. only the Pride palette
    -- in June). A palette that isn't available is still accepted when an art is saved.
    is_available BOOLEAN   NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_deleted BOOLEAN     NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT color_palettes_six_colors CHECK (cardinality(colors) = 6),
    CONSTRAINT color_palettes_hex_colors CHECK (array_to_string(colors, ',') ~ '^#[0-9A-F]{6}(,#[0-9A-F]{6}){5}$'),
    CONSTRAINT color_palettes_name_not_blank CHECK (btrim(name) <> '' AND name = btrim(name)),
    CONSTRAINT color_palettes_deleted_at_matches_is_deleted CHECK (is_deleted = (deleted_at IS NOT NULL))
);

-- Unique across every row, deleted ones included: saved arts accept any palette that ever
-- existed, so a name must always mean the same palette.
CREATE UNIQUE INDEX color_palettes_name_unique ON color_palettes (name);
CREATE UNIQUE INDEX color_palettes_position_unique ON color_palettes (position) WHERE NOT is_deleted;

CREATE TRIGGER color_palettes_set_audit_columns
    BEFORE UPDATE ON color_palettes
    FOR EACH ROW EXECUTE FUNCTION set_audit_columns();

-- The apps use the first palette as the default, so GET /color-palettes must never be empty.
-- Checked at commit, so a campaign switch can take several statements in one transaction.
CREATE FUNCTION check_color_palette_available() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM color_palettes WHERE is_available AND NOT is_deleted) THEN
        RAISE EXCEPTION 'At least one color palette must be available and not deleted';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER color_palettes_one_available
    AFTER UPDATE OR DELETE ON color_palettes
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_color_palette_available();

